export const messages: Record<Lang, Record<MessageKey, string>> = { en, bn };

const BN_DIGITS = '০১২৩৪৫৬৭৮৯';

export function localizeDigits(text: string, lang: Lang): string {
  return lang === 'bn' ? text.replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)]) : text;
}

export function translate(lang: Lang, key: MessageKey, vars: Record<string, string | number> = {}): string {
  const template = messages[lang][key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    name in vars ? localizeDigits(String(vars[name]), lang) : `{${name}}`,
  );
}

export function detectLang(): Lang {
  const nav = globalThis.navigator?.language?.toLowerCase() ?? '';
  return nav.startsWith('en') && !nav.includes('bd') && !nav.includes('in') ? 'en' : 'bn';
}
